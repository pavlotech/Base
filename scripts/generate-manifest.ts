import fs from "fs";
import path from "path";

const rootDir = process.cwd();
const generatedDir = path.join(rootDir, "internal", "generated");
const manifestPath = path.join(generatedDir, "manifest.ts");

const modulesDir = path.join(rootDir, "internal", "application", "modules");
const routesDir = path.join(rootDir, "internal", "application", "routes");

function getFiles(dir: string, suffix: string = ".ts"): string[] {
    if (!fs.existsSync(dir)) return [];
    const results: string[] = [];
    fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            results.push(...getFiles(full, suffix));
        } else if (entry.name.endsWith(suffix) && !entry.name.endsWith(".disabled")) {
            results.push(full);
        }
    });
    return results;
}

const moduleFiles = getFiles(modulesDir);
const routeFiles = getFiles(routesDir);

if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
}

const moduleImports = moduleFiles
    .map((file, i) => {
        const rel = path.relative(generatedDir, file).replace(/\\/g, "/").replace(/\.ts$/, "");
        const specifier = rel.startsWith(".") ? rel : `./${rel}`;
        return `import * as mod_${i} from "${specifier}";`;
    })
    .join("\n");

const routeImports = routeFiles
    .map((file, i) => {
        const rel = path.relative(generatedDir, file).replace(/\\/g, "/").replace(/\.ts$/, "");
        const specifier = rel.startsWith(".") ? rel : `./${rel}`;
        return `import * as route_${i} from "${specifier}";`;
    })
    .join("\n");

const content = `// This file is auto-generated by scripts/generate-manifest.ts. Do not edit manually.
${moduleImports}
${routeImports}

export const bundledModules: { file: string; module: any }[] = [
${moduleFiles
    .map((file, i) => {
        const norm = path.relative(rootDir, file).replace(/\\/g, "/");
        return `    { file: "${norm}", module: mod_${i} },`;
    })
    .join("\n")}
];

export const bundledRoutes: { file: string; module: any }[] = [
${routeFiles
    .map((file, i) => {
        const norm = path.relative(rootDir, file).replace(/\\/g, "/");
        return `    { file: "${norm}", module: route_${i} },`;
    })
    .join("\n")}
];
`;

fs.writeFileSync(manifestPath, content, "utf-8");
console.log(`[Manifest] Generated manifest with ${moduleFiles.length} module(s) and ${routeFiles.length} route(s).`);
